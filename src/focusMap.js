export function getFocusGroups(topicId) {
  return (detailGroupsById[topicId] || []).map((group, groupIndex) => {
    const labels = labelsById[topicId]?.[groupIndex];
    if (!labels || labels.length !== group.bullets.length + 1) throw new Error(`Focus labels out of sync: ${topicId}/${groupIndex}`);
    return {
      id: `group-${topicId}-${groupIndex}`, label: labels[0], title: group.title, cue: group.cue,
      items: group.bullets.map((detail, itemIndex) => ({
        id: `item-${topicId}-${groupIndex}-${itemIndex}`, label: labels[itemIndex + 1], detail,
      })),
    };
  });
}

export function buildFocusLayout(topicId, expandedGroupId) {
  const topic = topicById[topicId];
  if (!topic) return { nodes: [], edges: [] };
  const groups = getFocusGroups(topicId);
  const root = { id: `focus-${topicId}`, kind: "focus-root", label: topic.label, depth: 0, branchIndex: topic.branchIndex, x: 105, y: 380 };
  const nodes = [root], edges = [];
  const heights = groups.map((group) => group.id === expandedGroupId ? Math.max(58, group.items.length * 50 + 10) : 58);
  let top = 380 - heights.reduce((sum, height) => sum + height, 0) / 2;
  groups.forEach((group, index) => {
    const expanded = group.id === expandedGroupId;
    const parent = { ...group, kind: "group", expanded, depth: 1, branchIndex: topic.branchIndex, x: 330, y: top + heights[index] / 2 };
    nodes.push(parent);
    edges.push({ from: root, to: parent, branchIndex: topic.branchIndex, depth: 1 });
    if (expanded) {
      group.items.forEach((item, itemIndex) => {
        const child = { ...item, kind: "item", depth: 2, branchIndex: topic.branchIndex, x: 570, y: parent.y + (itemIndex - (group.items.length - 1) / 2) * 50 };
        nodes.push(child);
        edges.push({ from: parent, to: child, branchIndex: topic.branchIndex, depth: 2 });
      });
    }
    top += heights[index];
  });
  return { nodes, edges };
}
